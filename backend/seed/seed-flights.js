/* =========================================================
   DAILY SCHEDULE CONFLICT TRACKER
   ========================================================= */
class DaySchedule {
  constructor() {
    this.deps = new Map(); // cityId(string) → Set<depHour>
    this.arrs = new Map(); // cityId(string) → Set<arrHour>
  }
  _arrHour(depH, durH) { return Math.floor(depH + durH); }

  trySchedule(fromId, toId, durH, preferred) {
    for (const h of preferred) {
      const ah = this._arrHour(h, durH);
      const fd = this.deps.get(fromId) || new Set();
      const ta = this.arrs.get(toId)   || new Set();
      if (!fd.has(h) && !ta.has(ah)) {
        if (!this.deps.has(fromId)) this.deps.set(fromId, new Set());
        if (!this.arrs.has(toId))   this.arrs.set(toId,   new Set());
        this.deps.get(fromId).add(h);
        this.arrs.get(toId).add(ah);
        return h;
      }
    }
    return null;
  }
}

