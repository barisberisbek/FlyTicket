/**
 * Realistic 81-province flight seed for FlyTicket.
 * Clears all existing flights and generates ~3 weeks of data.
 * Run: node seed/seed-flights.js
 *
 * Frequency tiers:
 *   daily  – major hub routes (IST↔ANK 3x, IST↔IZM 2x, etc.)
 *   3pw    – medium city routes (Mon/Wed/Fri)
 *   2pw    – smaller city routes (Tue/Fri)
 *   1pw    – very small / remote cities (Thu)
 *   3pw-r  – regional feeder routes (Mon/Wed/Fri, local hubs)
 *
 * Conflict rule (mirrors flightRules.js):
 *   - No two departures from the same city in the same calendar hour on the same day.
 *   - No two arrivals   at   the same city in the same calendar hour on the same day.
 */

