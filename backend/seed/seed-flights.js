/* =========================================================
   MERGE ALL ROUTES
   ========================================================= */
const ALL_ROUTES = [
  ...IST_DAILY_OUT,
  ...IST_DAILY_RET,
  ...ANK_DAILY,
  ...IZM_ANT,
  ...MEDIUM_IST,
  ...MEDIUM_ANK,
  ...MEDIUM_IZM,
  ...SMALL_IST,
  ...SMALL_ANK,
  ...SMALL_IZM,
  ...SMALL_ANT,
  ...REMOTE_IST,
  ...REMOTE_ANK,
  ...REGIONAL,
];

/* =========================================================
   MAIN
   ========================================================= */
async function run() {
  await connectDB();

  // Build city lookup
  const cityDocs = await City.find({}, 'city_id _id');
  const cityMap  = Object.fromEntries(cityDocs.map((c) => [c.city_id, c._id]));

  // Clear existing flights
  const deleted = await Flight.deleteMany({});
  console.log(`Cleared ${deleted.deletedCount} existing flights.`);

  const now = new Date();
  let created = 0;
  let skipped = 0;

  for (let offset = 7; offset <= 27; offset++) {
    const dayOfWeek = offset % 7; // 0=Mon cycle
    const sched = new DaySchedule();

    const baseDate = new Date(Date.UTC(
      now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate() + offset,
    ));

    for (const route of ALL_ROUTES) {
      const [fromId, toId, durH, basePrice, seats, days, preferred] = route;
      if (!days.includes(dayOfWeek)) continue;

      const fromObjId = cityMap[fromId];
      const toObjId   = cityMap[toId];
      if (!fromObjId || !toObjId) { skipped++; continue; }

      const depHour = sched.trySchedule(fromId, toId, durH, preferred);
      if (depHour === null) {
        skipped++;
        continue;
      }

      // ±8% price variation rounded to 10
      const variation = Math.round((0.96 + Math.random() * 0.08) * basePrice / 10) * 10;
      const dep = new Date(baseDate.getTime() + depHour * 3600_000);
      const arr = new Date(dep.getTime() + Math.round(durH * 3600_000));

      await Flight.create({
        from_city:       fromObjId,
        to_city:         toObjId,
        departure_time:  dep,
        arrival_time:    arr,
        price:           variation,
        seats_total:     seats,
        seats_available: seats,
        booked_seats:    [],
      });
      created++;
    }
  }

  console.log(`Flights created : ${created}`);
  console.log(`Slots skipped   : ${skipped}`);
  await mongoose.disconnect();
  console.log('Done.');
}

run().catch((e) => { console.error(e); process.exit(1); });
